#!/usr/bin/env python
"""Backlog tool (stdlib only). Run from the project root.

  python tools/backlog.py build            regenerate backlog/BACKLOG.md, backlog/backlog.csv, backlog/tickets/*.md
  python tools/backlog.py check            validate deps, 1-6h rule, weekly load, cycles
  python tools/backlog.py next [-n 3]      next ready tickets (status todo, all deps done)
  python tools/backlog.py show T4.2.2      print one ticket
  python tools/backlog.py set T4.2.2 done  set status: todo | in_progress | blocked | done | cut
  python tools/backlog.py list [--week 3]  compact table
"""
import argparse
import csv
import importlib.util
import json
import sys
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "backlog" / "source" / "tickets.py"
STATUS = ROOT / "backlog" / "status.json"
OUT_DIR = ROOT / "backlog" / "tickets"
STATUSES = ["todo", "in_progress", "blocked", "done", "cut"]
WEEK_CAP = 10.0


def load():
    spec = importlib.util.spec_from_file_location("tickets_src", SRC)
    m = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(m)
    return m


def size(h):
    return "S" if h <= 2 else ("M" if h <= 4 else "L")


def load_status(ids):
    st = json.loads(STATUS.read_text()) if STATUS.exists() else {}
    for i in ids:
        st.setdefault(i, "todo")
    return {k: v for k, v in st.items() if k in ids}


def save_status(st):
    STATUS.write_text(json.dumps(dict(sorted(st.items())), indent=2) + "\n")


def by_id(m):
    return {x["id"]: x for x in m.T}


def sub_epic(m, tk):
    return m.STORIES[tk["story"]][0]


def render_ticket(m, tk, status):
    se = sub_epic(m, tk)
    s = m.STORIES[tk["story"]]
    wk = tk["week"] if tk["week"] else "unscheduled (stretch)"
    fm = [
        "---", f"id: {tk['id']}", f"title: \"{tk['title']}\"", f"type: {tk['type']}",
        f"epic: {m.EPIC['id']}", f"sub_epic: {se}", f"story: {tk['story']}",
        f"priority: {tk['prio']}", f"estimate_hours: {tk['est']}", f"size: {size(tk['est'])}",
        f"week: {tk['week'] if tk['week'] else 'null'}", f"status: {status}",
        f"depends_on: [{', '.join(tk['deps'])}]", "---", "",
    ]
    body = [
        f"# [{tk['id']}] {tk['title']}", "",
        f"- **Type:** {tk['type']}",
        f"- **Sub-epic:** {se} - {m.SUBEPICS[se]}",
        f"- **Story:** {tk['story']} - {s[1]}",
        f"- **Status:** {status}",
        f"- **Priority:** {tk['prio']}",
        f"- **Estimate:** {tk['est']} h ({size(tk['est'])})",
        f"- **Planned week:** {wk}",
        f"- **Dependencies:** {', '.join(tk['deps']) if tk['deps'] else 'none'}",
        f"- **Deliverable/artifact:** {tk['deliverable']}", "",
        "## Description", tk["desc"], "",
        "## Acceptance criteria",
    ] + [f"- [ ] {a}" for a in tk["ac"]] + [
        "", "## Agent notes",
        "Read CLAUDE.md first. Do not mark done until every box above is verified by running or inspecting the artifact.",
        "When finished: tick the boxes here, then `python tools/backlog.py set " + tk["id"] + " done`.", "",
    ]
    return "\n".join(fm + body)


def build():
    m = load()
    ids = [x["id"] for x in m.T]
    st = load_status(ids)
    save_status(st)
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    for old in OUT_DIR.glob("T*.md"):
        # preserve ticked checkboxes? Regeneration resets them; status.json is the durable state.
        old.unlink()
    for tk in m.T:
        (OUT_DIR / f"{tk['id']}.md").write_text(render_ticket(m, tk, st[tk["id"]]), encoding="utf-8")

    # BACKLOG.md
    L = [f"# Backlog - {m.EPIC['id']}: {m.EPIC['title']}", "",
         "_Generated by `python tools/backlog.py build` from `backlog/source/tickets.py`. Do not edit by hand._", "",
         f"**Goal:** {m.EPIC['goal']}", ""]
    tot = sum(x["est"] for x in m.T)
    sched = defaultdict(float)
    for x in m.T:
        if x["week"]:
            sched[x["week"]] += x["est"]
    L += ["## Summary", "",
          f"- Tickets: {len(m.T)} | Stories: {len(m.STORIES)} | Sub-epics: {len(m.SUBEPICS)}",
          f"- Total estimate: {tot:.1f} h | Scheduled (P0/P1): {sum(sched.values()):.1f} h | Stretch (P2, unscheduled): {tot - sum(sched.values()):.1f} h", "",
          "| Week | Hours | Tickets |", "|---|---|---|"]
    for w in sorted(sched):
        L.append(f"| {w} | {sched[w]:.1f} | " + ", ".join(x["id"] for x in m.T if x["week"] == w) + " |")
    L += ["", "## Sub-epics", ""]
    for se, name in m.SUBEPICS.items():
        h = sum(x["est"] for x in m.T if sub_epic(m, x) == se)
        L.append(f"- **{se}** {name} ({h:.1f} h)")
    for se, name in m.SUBEPICS.items():
        L += ["", "---", f"## {se}: {name}", ""]
        for sid, s in m.STORIES.items():
            if s[0] != se:
                continue
            L += [f"### [{sid}] {s[1]}", "- Type: Story", f"- Sub-epic: {se}",
                  f"- As a **{s[2]}**, I want **{s[3]}**, so that **{s[4]}**.", ""]
            for tk in [x for x in m.T if x["story"] == sid]:
                L += [f"**[{tk['id']}] {tk['title']}**",
                      f"- Type: {tk['type']}", f"- Sub-epic: {se}", f"- Story: {sid}",
                      f"- Description: {tk['desc']}", "- Acceptance criteria:"]
                L += [f"  - [ ] {a}" for a in tk["ac"]]
                L += [f"- Dependencies: {', '.join(tk['deps']) if tk['deps'] else 'none'}",
                      f"- Estimate: {tk['est']} h ({size(tk['est'])})", f"- Priority: {tk['prio']}",
                      f"- Week: {tk['week'] if tk['week'] else 'stretch'}",
                      f"- Deliverable/artifact: {tk['deliverable']}", ""]
    (ROOT / "backlog" / "BACKLOG.md").write_text("\n".join(L), encoding="utf-8")

    # CSV (generic import: Jira / Linear / Notion / GitHub Projects)
    with (ROOT / "backlog" / "backlog.csv").open("w", newline="", encoding="utf-8") as f:
        w = csv.writer(f)
        w.writerow(["ID", "Type", "Parent", "Title", "Description", "Acceptance Criteria", "Priority",
                    "Estimate (h)", "Size", "Week", "Dependencies", "Labels", "Status", "Deliverable"])
        w.writerow([m.EPIC["id"], "Epic", "", m.EPIC["title"], m.EPIC["goal"], "", "P0", "", "", "", "", "", "todo", ""])
        for se, name in m.SUBEPICS.items():
            w.writerow([se, "Epic", m.EPIC["id"], name, "", "", "", "", "", "", "", "sub-epic", "todo", ""])
        for sid, s in m.STORIES.items():
            w.writerow([sid, "Story", s[0], s[1], f"As a {s[2]}, I want {s[3]}, so that {s[4]}.", "", "", "", "", "", "", s[0], "todo", ""])
        for tk in m.T:
            w.writerow([tk["id"], tk["type"], tk["story"], tk["title"], tk["desc"],
                        "\n".join("- [ ] " + a for a in tk["ac"]), tk["prio"], tk["est"], size(tk["est"]),
                        tk["week"] or "", ";".join(tk["deps"]), sub_epic(m, tk), st[tk["id"]], tk["deliverable"]])
    print(f"built {len(m.T)} tickets -> backlog/tickets/, backlog/BACKLOG.md, backlog/backlog.csv")


def check():
    m = load()
    d = by_id(m)
    errs = []
    for tk in m.T:
        if not (1 <= tk["est"] <= 6):
            errs.append(f"{tk['id']}: estimate {tk['est']}h outside 1-6h")
        if tk["story"] not in m.STORIES:
            errs.append(f"{tk['id']}: unknown story")
        if not tk["ac"]:
            errs.append(f"{tk['id']}: no acceptance criteria")
        for dep in tk["deps"]:
            if dep not in d:
                errs.append(f"{tk['id']}: unknown dependency {dep}")
            elif tk["week"] and d[dep]["week"] and d[dep]["week"] > tk["week"]:
                errs.append(f"{tk['id']}: depends on {dep} scheduled later (week {d[dep]['week']})")
            elif tk["week"] and d[dep]["week"] is None:
                errs.append(f"{tk['id']}: scheduled but depends on unscheduled stretch ticket {dep}")
        if tk["type"] == "Spike" and "TIME BOX" not in tk["desc"]:
            errs.append(f"{tk['id']}: spike without TIME BOX")
    # cycles
    seen, stack = set(), set()
    def dfs(n):
        if n in stack:
            errs.append(f"cycle at {n}"); return
        if n in seen:
            return
        seen.add(n); stack.add(n)
        for x in d[n]["deps"]:
            if x in d: dfs(x)
        stack.discard(n)
    for n in d: dfs(n)
    load_w = defaultdict(float)
    for tk in m.T:
        if tk["week"]:
            load_w[tk["week"]] += tk["est"]
    for w, h in sorted(load_w.items()):
        if h > WEEK_CAP:
            errs.append(f"week {w}: {h}h exceeds {WEEK_CAP}h")
    for e in errs:
        print("ERROR", e)
    print("weekly load:", {w: h for w, h in sorted(load_w.items())})
    print("OK" if not errs else f"{len(errs)} problem(s)")
    return 1 if errs else 0


def ready(m, st):
    by_id(m)
    out = []
    for tk in m.T:
        if st[tk["id"]] != "todo":
            continue
        if all(st.get(x) in ("done", "cut") for x in tk["deps"]):
            out.append(tk)
    prio = {"P0": 0, "P1": 1, "P2": 2}
    out.sort(key=lambda x: (x["week"] or 99, prio[x["prio"]], x["id"]))
    return out


def main():
    ap = argparse.ArgumentParser()
    sp = ap.add_subparsers(dest="cmd", required=True)
    sp.add_parser("build"); sp.add_parser("check")
    n = sp.add_parser("next"); n.add_argument("-n", type=int, default=3)
    s = sp.add_parser("show"); s.add_argument("id")
    z = sp.add_parser("set"); z.add_argument("id"); z.add_argument("status", choices=STATUSES)
    l = sp.add_parser("list"); l.add_argument("--week", type=int)
    a = ap.parse_args()
    if a.cmd == "build": build(); return 0
    if a.cmd == "check": return check()
    m = load(); st = load_status([x["id"] for x in m.T]); d = by_id(m)
    if a.cmd == "next":
        for tk in ready(m, st)[: a.n]:
            print(f"{tk['id']:8} W{tk['week'] or '-'} {tk['prio']} {tk['est']:>4}h  {tk['title']}   -> backlog/tickets/{tk['id']}.md")
    elif a.cmd == "show":
        print((OUT_DIR / f"{a.id}.md").read_text(encoding="utf-8"))
    elif a.cmd == "set":
        if a.id not in d: print("unknown ticket"); return 1
        st[a.id] = a.status; save_status(st); build_quiet()
        print(f"{a.id} -> {a.status}")
    elif a.cmd == "list":
        for tk in m.T:
            if a.week and tk["week"] != a.week: continue
            print(f"{tk['id']:8} W{str(tk['week'] or '-'):2} {tk['prio']} {tk['est']:>4}h {st[tk['id']]:11} {tk['title']}")
    return 0


def build_quiet():
    import contextlib
    import io
    with contextlib.redirect_stdout(io.StringIO()):
        build()


if __name__ == "__main__":
    sys.exit(main())
