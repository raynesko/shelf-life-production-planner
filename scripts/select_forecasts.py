"""T3.2.3: select forecast models on the validation year; report test accuracy; export planner inputs.

Outputs: configs/forecast_selection.yaml, results/forecast/headline_forecast.csv,
         results/forecast/forecasts_test.parquet, results/forecast/forecasts_validation.parquet
Run: python scripts/select_forecasts.py
"""
from __future__ import annotations

from pathlib import Path

import pandas as pd
import yaml

from shelflife.forecast.selection import assemble, headline, select

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "results" / "forecast"
# Variants rejected on VALIDATION evidence in their own ticket (not candidates for selection):
# - prophet: holiday-free Prophet; T3.2.2 kept holidays (validation WAPE 12.13% -> 11.55%), see forecasting.md
EXCLUDED = {"prophet"}


def main() -> None:
    files = [OUT / "benchmark_forecasts.parquet"] + sorted(p for p in OUT.glob("*_forecasts.parquet")
                                                            if p.name != "benchmark_forecasts.parquet"
                                                            and p.name.removesuffix("_forecasts.parquet") not in EXCLUDED)
    fc = pd.concat([pd.read_parquet(f) for f in files], ignore_index=True)
    per_sku, glob, table = select(fc[fc.window == "validation"])
    hl = headline(assemble(fc[fc.window == "test"], per_sku), fc[fc.window == "test"])
    hl.round(3).to_csv(OUT / "headline_forecast.csv", index=False)
    assemble(fc[fc.window == "test"], per_sku).to_parquet(OUT / "forecasts_test.parquet", index=False)
    assemble(fc[fc.window == "validation"], per_sku).to_parquet(OUT / "forecasts_validation.parquet", index=False)
    (ROOT / "configs" / "forecast_selection.yaml").write_text(yaml.safe_dump({
        "note": "Generated by scripts/select_forecasts.py. Per-SKU model = lowest VALIDATION WAPE (test never read).",
        "candidates": sorted(fc.model.unique()),
        "per_sku": per_sku,
        "global_best_on_validation": glob,
        "validation_wape": {s: {m: round(float(v), 3) for m, v in g.set_index("model").val_wape.items()}
                            for s, g in table.groupby("sku_id")},
    }, sort_keys=False), encoding="utf-8")
    print("per-SKU choice:", per_sku)
    print("global best on validation:", glob)
    print(hl.round(2).to_string(index=False))


if __name__ == "__main__":
    main()
