"""T2.2.2 capacity calibration (+ T3.1.1 window file).

Finds one demand scale factor k (plant cases per week = k x Favorita units per week, same k for all SKUs so
the real demand mix is preserved) such that baseline B1 loads the line to a mean utilisation of 85%
((run + changeover hours) / available hours). Uses ONLY weeks before the test year (no test leakage).
The 85% target is an assumption (A-04), swept 70-95% in T5.2.1.

k is a plant-design assumption fixed once, before any result (ADR-011). If configs/calibration.yaml exists, this
script does NOT re-derive k: it only checks that the current B1 still loads the line within +/- TOL of the target
with the committed k, and fails otherwise. Re-deriving k after a baseline code change would silently re-scale the
plant and every result. Use --recalibrate only for a deliberate, recorded change.

Run: python scripts/calibrate.py [--recalibrate]  ->  configs/windows.yaml (+ configs/calibration.yaml)
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

import numpy as np
import pandas as pd
import yaml

from shelflife.forecast.backtest import make_windows
from shelflife.plant.changeover import build_matrix
from shelflife.plant.config import load
from shelflife.sim import kpis
from shelflife.sim.baseline import BaselineB1
from shelflife.sim.engine import SimPlant, simulate_policy

ROOT = Path(__file__).resolve().parents[1]
TARGET_UTIL = 0.85
TOL = 0.02
WARMUP = 4


def demand_matrix(panel: pd.DataFrame, sku_ids: list[str], end_before: pd.Timestamp) -> np.ndarray:
    w = panel[panel.week_start < end_before].pivot(index="sku_id", columns="week_start", values="units")
    return w.loc[sku_ids].to_numpy(float)


def run_baseline(k: float, plant: SimPlant, cfg, units: np.ndarray):
    d = units * k
    b1 = BaselineB1.from_config(cfg, plant)
    r, _ = simulate_policy(plant, b1, d[:, WARMUP:], d[:, :WARMUP], initial_last_sku=0)
    return r


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--recalibrate", action="store_true")
    a = ap.parse_args()
    cfg = load()
    plant = SimPlant.from_config(cfg, build_matrix(cfg))
    panel = pd.read_parquet(ROOT / "data" / "processed" / "demand_weekly.parquet")
    win = make_windows(panel.week_start)
    (ROOT / "configs" / "windows.yaml").write_text(yaml.safe_dump({
        "note": "Generated by scripts/calibrate.py via forecast.backtest.make_windows. Test window is for reporting only.",
        **win.to_dict(),
        "train_weeks": int((pd.DatetimeIndex(panel.week_start.unique()) < win.val_start).sum()),
    }, sort_keys=False), encoding="utf-8")

    units = demand_matrix(panel, plant.sku_ids, win.test_start)
    cal = ROOT / "configs" / "calibration.yaml"
    if cal.exists() and not a.recalibrate:
        k = yaml.safe_load(cal.read_text(encoding="utf-8"))["scale_factor"]
        u = kpis.utilisation(run_baseline(k, plant, cfg, units))
        ok = abs(u - TARGET_UTIL) <= TOL
        print(f"calibration frozen (ADR-011): k = {k}; current B1 utilisation {u:.4f} "
              f"(target {TARGET_UTIL} +/- {TOL}): {'OK' if ok else 'OUT OF RANGE'}")
        if not ok:
            sys.exit("calibration check failed; re-calibrate deliberately with --recalibrate and record an ADR")
        return
    lo, hi = 0.01, 2.0
    for _ in range(40):
        mid = (lo + hi) / 2
        if kpis.utilisation(run_baseline(mid, plant, cfg, units)) < TARGET_UTIL:
            lo = mid
        else:
            hi = mid
    k = round((lo + hi) / 2, 6)
    r = run_baseline(k, plant, cfg, units)
    s = kpis.summarise(r)
    out = {
        "note": "Generated by scripts/calibrate.py. cases = scale_factor x Favorita units (all SKUs). Assumption A-04.",
        "scale_factor": k,
        "target_mean_utilisation": TARGET_UTIL,
        "achieved_mean_utilisation": round(s["utilisation"], 4),
        "calibration_window": {"from": str(panel.week_start.min().date()), "to_before": str(win.test_start.date()),
                               "warmup_weeks": WARMUP, "simulated_weeks": int(units.shape[1] - WARMUP)},
        "mean_cases_per_week_all_skus": round(float(units.sum(axis=0).mean() * k), 1),
        "baseline_kpis_on_calibration_window": {key: round(float(v), 4) for key, v in s.items()},
        "baseline_hours_per_week": {
            "run": round(float(r.week.run_hours.mean()), 2),
            "changeover": round(float(r.week.changeover_hours.mean()), 2),
            "allergen_clean": round(float(r.week.allergen_clean_hours.mean()), 2),
            "capacity_breach_weeks": int(r.week.capacity_breach.sum()),
        },
    }
    (ROOT / "configs" / "calibration.yaml").write_text(yaml.safe_dump(out, sort_keys=False), encoding="utf-8")
    print(yaml.safe_dump(out, sort_keys=False))


if __name__ == "__main__":
    main()
